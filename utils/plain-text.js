/**
 * 诊断室里老师说的话按纯文本呈现：真人老师不会发 **加粗**、# 标题或者列表符号，
 * 模型输出里的 Markdown 记号在这里全部剥掉，只留下文字本身。
 *
 * 为什么在 JS 里做而不是在 WXML 里用 wxs 做（2026-09-22）：
 * 渲染层每多一个 wxs 函数调用，就多一处只有真机才暴露的失败点——一旦它没算出东西，
 * 气泡就是空的，页面不会报错，排查起来只能靠猜。放在 JS 里，文字在进 data 之前就已经是最终形态，
 * 模板只写 {{item.text}}，和学生自己的气泡走同一条路径；而且这一段逻辑可以直接单测。
 */

const RULES = [
  // 代码围栏与行内代码：留内容，去记号
  [/```[a-zA-Z0-9]*/g, ''],
  [/`([^`]*)`/g, '$1'],
  // 加粗与斜体（这条是重点：老师的话里不能出现加粗）
  [/\*\*([\s\S]+?)\*\*/g, '$1'],
  [/__([\s\S]+?)__/g, '$1'],
  [/\*([^*\n]+?)\*/g, '$1'],
  [/(^|[\s(])_([^_\n]+?)_/g, '$1$2'],
  // 链接与图片：只留可读文字
  [/!\[([^\]]*)\]\([^)]*\)/g, '$1'],
  [/\[([^\]]*)\]\([^)]*\)/g, '$1'],
  // 标题、引用、列表、分隔线的行首记号
  [/^[ \t]*#{1,6}[ \t]*/gm, ''],
  [/^[ \t]*>[ \t]?/gm, ''],
  [/^[ \t]*[-*+][ \t]+/gm, ''],
  [/^[ \t]*(\d+)\.[ \t]+/gm, '$1. '],
  [/^[ \t]*([-*_][ \t]*){3,}[ \t]*$/gm, ''],
  // 剥完记号后留下的多余空行收一收
  [/\n{3,}/g, '\n\n']
]

function stripMarkdown(value) {
  let text = value === null || value === undefined ? '' : String(value)
  if (!text) return ''
  for (const [pattern, replacement] of RULES) text = text.replace(pattern, replacement)
  return text.trim()
}

module.exports = { stripMarkdown }
